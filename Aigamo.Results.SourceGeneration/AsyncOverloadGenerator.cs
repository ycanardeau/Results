using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Aigamo.Results.SourceGeneration;

/// <summary>
/// Generates the Task-lifted async overloads for extension methods that are
/// marked with <c>[GenerateAsyncOverloads]</c>.
///
/// For a hand-written synchronous "core" of the shape
/// <c>static RET Name(this SRC source, Func&lt;...&gt; selector, ...)</c>
/// three overloads are produced:
///   A. Task source, sync selector    : (await source).Name(selector)
///   B. sync source, async selector    : the core body with `await` inserted at each selector call
///   C. Task source, async selector    : await (await source).Name(asyncSelector)
///
/// The core must invoke each selector parameter directly by name (imperative
/// style, no Match/lambda wrapping) so that inserting `await` at the call site
/// is a valid, local transformation.
/// </summary>
[Generator]
public sealed class AsyncOverloadGenerator : IIncrementalGenerator
{
	private const string AttrNamespace = $"{nameof(Aigamo)}.{nameof(Results)}";
	private const string AttrName = "GenerateAsyncOverloadsAttribute";
	private const string AttrFullName = AttrNamespace + "." + AttrName;

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		context.RegisterPostInitializationOutput(static ctx =>
			ctx.AddSource(
				"GenerateAsyncOverloadsAttribute.g.cs",
				SourceText.From(
					$$"""
					// <auto-generated/>
					#nullable enable
					namespace {{AttrNamespace}}
					{
					    /// <summary>
					    /// Marks a synchronous extension-method "core" so that the source
					    /// generator emits its Task-lifted async overloads.
					    /// </summary>
					    [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = false, Inherited = false)]
					    internal sealed class {{AttrName}} : global::System.Attribute
					    {
					    }
					}
					""",
					Encoding.UTF8
				)
			)
		);

		var models = context
			.SyntaxProvider.ForAttributeWithMetadataName(
				AttrFullName,
				predicate: static (node, _) => node is MethodDeclarationSyntax,
				transform: static (ctx, _) => Extract(ctx)
			)
			.Where(static m => m is not null)
			.Select(static (m, _) => m!);

		context.RegisterSourceOutput(models.Collect(), static (spc, all) => Emit(spc, all));
	}

	// ---- extraction -------------------------------------------------------

	private static MethodModel? Extract(GeneratorAttributeSyntaxContext ctx)
	{
		if (ctx.TargetSymbol is not IMethodSymbol method)
			return null;
		if (ctx.TargetNode is not MethodDeclarationSyntax decl)
			return null;
		if (!method.IsStatic || !method.IsExtensionMethod || method.Parameters.Length == 0)
			return null;
		if (method.ContainingType is not { } containing)
			return null;

		var ns = method.ContainingNamespace.IsGlobalNamespace
			? string.Empty
			: method.ContainingNamespace.ToDisplayString();

		var parameters = new List<ParamInfo>();
		var selectorNames = new HashSet<string>();
		for (var i = 0; i < decl.ParameterList.Parameters.Count; i++)
		{
			var p = decl.ParameterList.Parameters[i];
			var name = p.Identifier.Text;
			var typeText = p.Type?.ToString() ?? "object";
			var isSource = i == 0 && p.Modifiers.Any(m => m.IsKind(SyntaxKind.ThisKeyword));
			var asyncType = p.Type is null ? null : AsyncifyDelegate(p.Type);
			var isSelector = !isSource && asyncType is not null;
			if (isSelector)
				selectorNames.Add(name);
			parameters.Add(
				new ParamInfo(
					RawText: p.ToString().Trim(),
					TypeText: typeText,
					Name: name,
					IsSource: isSource,
					IsSelector: isSelector,
					AsyncTypeText: asyncType
				)
			);
		}

		if (!parameters[0].IsSource)
			return null;

		// Build the async-selector body (variant B). Selector calls are lifted in
		// two shapes: a direct invocation `sel(x)` becomes `await sel(x)...`, and a
		// selector call inside a `Match` lambda makes that branch async, wraps the
		// sibling branch in Task.FromResult, and awaits the Match.
		string asyncBody;
		var rewriter = new AsyncSelectorRewriter(selectorNames);
		if (decl.Body is { } block)
		{
			asyncBody = rewriter.Visit(block).NormalizeWhitespace().ToFullString();
		}
		else if (decl.ExpressionBody is { } arrow)
		{
			var expr = (ExpressionSyntax)rewriter.Visit(arrow.Expression);
			asyncBody = "=> " + expr.NormalizeWhitespace().ToFullString() + ";";
		}
		else
		{
			return null;
		}

		return new MethodModel(
			Namespace: ns,
			ClassAccessibility: AccessibilityKeyword(containing.DeclaredAccessibility),
			ClassName: containing.Name,
			MethodAccessibility: AccessibilityKeyword(method.DeclaredAccessibility),
			MethodName: method.Name,
			TypeParams: decl.TypeParameterList?.ToString() ?? string.Empty,
			Constraints: string.Join(" ", decl.ConstraintClauses.Select(c => c.ToString())),
			ReturnType: decl.ReturnType.ToString(),
			Parameters: [.. parameters],
			AsyncSelectorBody: asyncBody,
			HasSelector: selectorNames.Count > 0
		);
	}

	/// <summary>
	/// Returns the async form of a Func/Action delegate type, or null if the
	/// type is not a delegate we lift.
	/// e.g. Func&lt;T,R&gt; -&gt; Func&lt;T,Task&lt;R&gt;&gt;, Action&lt;T&gt; -&gt; Func&lt;T,Task&gt;, Action -&gt; Func&lt;Task&gt;.
	/// </summary>
	private static string? AsyncifyDelegate(TypeSyntax type)
	{
		switch (type)
		{
			case GenericNameSyntax g:
			{
				var id = g.Identifier.Text;
				var args = g.TypeArgumentList.Arguments.Select(a => a.ToString()).ToList();
				if (id == "Func")
				{
					if (args.Count == 0)
						return null;
					var inputs = args.Take(args.Count - 1);
					var ret = args[args.Count - 1];
					return "Func<" + string.Join(", ", inputs.Concat([$"Task<{ret}>"])) + ">";
				}
				if (id == "Action")
				{
					return "Func<" + string.Join(", ", args.Concat(["Task"])) + ">";
				}
				return null;
			}
			case IdentifierNameSyntax { Identifier.Text: "Action" }:
				return "Func<Task>";
			case QualifiedNameSyntax q:
				return AsyncifyDelegate(q.Right);
			default:
				return null;
		}
	}

	// ---- emission ---------------------------------------------------------

	private static void Emit(SourceProductionContext spc, ImmutableArray<MethodModel> models)
	{
		if (models.IsDefaultOrEmpty)
			return;

		foreach (var group in models.GroupBy(m => (m.Namespace, m.ClassName)))
		{
			var sb = new StringBuilder();
			sb.AppendLine("// <auto-generated/>");
			sb.AppendLine("#nullable enable");
			sb.AppendLine("using System;");
			sb.AppendLine("using System.Threading.Tasks;");
			sb.AppendLine();

			var hasNs = !string.IsNullOrEmpty(group.Key.Namespace);
			var indent = "";
			if (hasNs)
			{
				sb.AppendLine($"namespace {group.Key.Namespace}");
				sb.AppendLine("{");
				indent = "    ";
			}

			var first = group.First();
			sb.AppendLine(
				$"{indent}{first.ClassAccessibility} static partial class {first.ClassName}"
			);
			sb.AppendLine($"{indent}{{");

			foreach (var m in group)
			{
				EmitVariantA(sb, m, indent + "    ");
				if (m.HasSelector)
				{
					EmitVariantB(sb, m, indent + "    ");
					EmitVariantC(sb, m, indent + "    ");
				}
			}

			sb.AppendLine($"{indent}}}");
			if (hasNs)
				sb.AppendLine("}");

			var hint =
				(hasNs ? group.Key.Namespace + "." : "") + first.ClassName + ".AsyncOverloads.g.cs";
			spc.AddSource(hint, SourceText.From(sb.ToString(), Encoding.UTF8));
		}
	}

	// A. Task source, sync selector: (await source).Name(args)
	private static void EmitVariantA(StringBuilder sb, MethodModel m, string indent)
	{
		var src = m.Parameters[0];
		var ps = m.Parameters.Select(p =>
			p.IsSource ? $"this Task<{p.TypeText}> {p.Name}" : p.RawText
		);
		var args = string.Join(", ", m.Parameters.Where(p => !p.IsSource).Select(p => p.Name));

		sb.AppendLine(
			$"{indent}{m.MethodAccessibility} static async Task<{m.ReturnType}> {m.MethodName}{m.TypeParams}({string.Join(", ", ps)}){Constraints(m)}"
		);
		sb.AppendLine(
			$"{indent}    => (await {src.Name}.ConfigureAwait(false)).{m.MethodName}({args});"
		);
		sb.AppendLine();
	}

	// B. sync source, async selector: core body with `await` inserted at selector calls
	private static void EmitVariantB(StringBuilder sb, MethodModel m, string indent)
	{
		var ps = m.Parameters.Select(RenderAsyncParam);
		sb.AppendLine(
			$"{indent}{m.MethodAccessibility} static async Task<{m.ReturnType}> {m.MethodName}{m.TypeParams}({string.Join(", ", ps)}){Constraints(m)}"
		);
		foreach (var line in Reindent(m.AsyncSelectorBody, indent))
			sb.AppendLine(line);
		sb.AppendLine();
	}

	// C. Task source, async selector: await (await source).Name(asyncArgs)
	private static void EmitVariantC(StringBuilder sb, MethodModel m, string indent)
	{
		var src = m.Parameters[0];
		var ps = m.Parameters.Select(p =>
			p.IsSource ? $"this Task<{p.TypeText}> {p.Name}" : RenderAsyncParam(p)
		);
		var args = string.Join(", ", m.Parameters.Where(p => !p.IsSource).Select(p => p.Name));

		sb.AppendLine(
			$"{indent}{m.MethodAccessibility} static async Task<{m.ReturnType}> {m.MethodName}{m.TypeParams}({string.Join(", ", ps)}){Constraints(m)}"
		);
		sb.AppendLine(
			$"{indent}    => await (await {src.Name}.ConfigureAwait(false)).{m.MethodName}({args}).ConfigureAwait(false);"
		);
		sb.AppendLine();
	}

	// Normalizes the copied core body: strips the smallest common leading
	// whitespace, converts tabs to 4 spaces, and re-indents under `indent`.
	private static IEnumerable<string> Reindent(string body, string indent)
	{
		var lines = body.Replace("\r\n", "\n")
			.Split('\n')
			.Select(l => l.Replace("\t", "    "))
			.ToList();
		while (lines.Count > 0 && lines[0].Trim().Length == 0)
			lines.RemoveAt(0);
		while (lines.Count > 0 && lines[lines.Count - 1].Trim().Length == 0)
			lines.RemoveAt(lines.Count - 1);

		var min = lines
			.Where(l => l.Trim().Length > 0)
			.Select(l => l.Length - l.TrimStart().Length)
			.DefaultIfEmpty(0)
			.Min();

		foreach (var l in lines)
			yield return l.Trim().Length == 0 ? string.Empty : indent + l.Substring(min);
	}

	private static string RenderAsyncParam(ParamInfo p)
	{
		if (p.IsSource)
			return $"this {p.TypeText} {p.Name}";
		if (p.IsSelector && p.AsyncTypeText is not null)
			return $"{p.AsyncTypeText} {p.Name}";
		return p.RawText;
	}

	private static string Constraints(MethodModel m) =>
		string.IsNullOrEmpty(m.Constraints) ? string.Empty : " " + m.Constraints;

	private static string AccessibilityKeyword(Accessibility a) =>
		a switch
		{
			Accessibility.Public => "public",
			Accessibility.Internal => "internal",
			Accessibility.Protected => "protected",
			Accessibility.ProtectedOrInternal => "protected internal",
			Accessibility.ProtectedAndInternal => "private protected",
			Accessibility.Private => "private",
			_ => "internal",
		};

	// ---- models -----------------------------------------------------------

	private sealed record ParamInfo(
		string RawText,
		string TypeText,
		string Name,
		bool IsSource,
		bool IsSelector,
		string? AsyncTypeText
	);

	private sealed record MethodModel(
		string Namespace,
		string ClassAccessibility,
		string ClassName,
		string MethodAccessibility,
		string MethodName,
		string TypeParams,
		string Constraints,
		string ReturnType,
		ImmutableArray<ParamInfo> Parameters,
		string AsyncSelectorBody,
		bool HasSelector
	);

	/// <summary>
	/// Lifts selector invocations to async. Handles two shapes:
	/// <list type="bullet">
	/// <item>a direct call <c>sel(x)</c> becomes <c>await sel(x).ConfigureAwait(false)</c>;</item>
	/// <item>an invocation whose lambda arguments call a selector (e.g. <c>Match</c>):
	/// the lambdas that call a selector become <c>async</c> with their selector calls
	/// awaited, the sibling lambdas are wrapped in <c>Task.FromResult(...)</c>, and the
	/// whole call is awaited.</item>
	/// </list>
	/// </summary>
	private sealed class AsyncSelectorRewriter : CSharpSyntaxRewriter
	{
		private readonly HashSet<string> _selectorNames;

		public AsyncSelectorRewriter(HashSet<string> selectorNames) =>
			_selectorNames = selectorNames;

		public override SyntaxNode? VisitInvocationExpression(InvocationExpressionSyntax node)
		{
			// Shape 2: a higher-order call (Match, ...) whose lambda arguments call a selector.
			if (HasSelectorCallingLambdaArg(node))
				return LiftLambdaArgInvocation(node);

			var visited = (InvocationExpressionSyntax)base.VisitInvocationExpression(node)!;

			// Shape 1: a direct selector invocation.
			if (
				visited.Expression is IdentifierNameSyntax id
				&& _selectorNames.Contains(id.Identifier.Text)
			)
			{
				// Parenthesize only when the awaited call is the receiver of a further
				// member access (`binder(x).Map(...)`); as a bare statement/expression a
				// parenthesized await would be invalid.
				var isReceiver =
					node.Parent is MemberAccessExpressionSyntax member && member.Expression == node;
				return AwaitInPlace(visited, isReceiver);
			}

			return visited;
		}

		private bool HasSelectorCallingLambdaArg(InvocationExpressionSyntax node) =>
			node.ArgumentList.Arguments.Any(a =>
				a.Expression is LambdaExpressionSyntax lambda && LambdaCallsSelector(lambda)
			);

		private bool LambdaCallsSelector(LambdaExpressionSyntax lambda) =>
			lambda
				.DescendantNodes()
				.OfType<InvocationExpressionSyntax>()
				.Any(i =>
					i.Expression is IdentifierNameSyntax id
					&& _selectorNames.Contains(id.Identifier.Text)
				);

		private ExpressionSyntax LiftLambdaArgInvocation(InvocationExpressionSyntax node)
		{
			var newArgs = node.ArgumentList.Arguments.Select(a =>
			{
				var replacement = a.Expression switch
				{
					LambdaExpressionSyntax lambda when LambdaCallsSelector(lambda) =>
						MakeLambdaAsync(lambda),
					LambdaExpressionSyntax lambda => WrapLambdaResultInTask(lambda),
					// A non-lambda branch (e.g. a method group `Result.Error<R, E>`) is
					// invoked and its result lifted so it matches the async sibling's Task.
					_ => WrapExpressionResultInTask(a.Expression),
				};
				return a.WithExpression(replacement);
			});

			var newInvocation = node.WithArgumentList(
				node.ArgumentList.WithArguments(SyntaxFactory.SeparatedList(newArgs))
			);

			return SyntaxFactory.ParseExpression(
				$"await {newInvocation.ToString()}.ConfigureAwait(false)"
			);
		}

		// `x => body` -> `async x => bodyWithAwaitedSelectorCalls`
		private ExpressionSyntax MakeLambdaAsync(LambdaExpressionSyntax lambda)
		{
			var awaited = (LambdaExpressionSyntax)base.Visit(lambda)!; // insert awaits at selector calls
			return SyntaxFactory.ParseExpression("async " + awaited.ToString());
		}

		// `x => body` -> `x => Task.FromResult(body)` (expression-bodied lambdas)
		private ExpressionSyntax WrapLambdaResultInTask(LambdaExpressionSyntax lambda)
		{
			var header = lambda switch
			{
				SimpleLambdaExpressionSyntax s => s.Parameter.ToString(),
				ParenthesizedLambdaExpressionSyntax p => p.ParameterList.ToString(),
				_ => "_",
			};
			var body = lambda.Body is ExpressionSyntax e ? e.ToString() : lambda.Body.ToString();
			return SyntaxFactory.ParseExpression($"{header} => Task.FromResult({body})");
		}

		// A method group (or other delegate-valued expression) used as a branch:
		// `Result.Error<R, E>` -> `__arg => Task.FromResult(Result.Error<R, E>(__arg))`.
		private ExpressionSyntax WrapExpressionResultInTask(ExpressionSyntax expr) =>
			SyntaxFactory.ParseExpression($"__arg => Task.FromResult({expr.ToString()}(__arg))");

		// When `parenthesize` is set the await binds tightly so a following member access
		// applies to the awaited value (`(await binder(x).ConfigureAwait(false)).Map(...)`)
		// rather than to the whole chain.
		private static ExpressionSyntax AwaitInPlace(
			InvocationExpressionSyntax invocation,
			bool parenthesize
		)
		{
			var awaited = $"await {invocation.ToString()}.ConfigureAwait(false)";
			return SyntaxFactory
				.ParseExpression(parenthesize ? $"({awaited})" : awaited)
				.WithTriviaFrom(invocation);
		}
	}
}
